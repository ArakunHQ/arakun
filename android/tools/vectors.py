#!/usr/bin/env python3
"""Turns the brand's SVGs into Android vector drawables.

The line icons in assets/icons (24x24, stroked paths and circles) become
app/src/main/res/drawable/ic_<name>.xml, drawn in black for the app to tint,
and assets/brand/raccoon.svg becomes the launcher icon's foreground and the
notification icon. Run it
again after an icon changes or the app uses a new one:

    python3 android/tools/vectors.py
"""

import os
import re
import sys
import xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
ICONS = os.path.join(ROOT, "assets", "icons")
OUT = os.path.join(HERE, "..", "app", "src", "main", "res", "drawable")

# The icons the app draws; keep in step with Icon(...) calls under app/src.
USED = """
ai-idea alert-circle arrow-down01 arrow-left01 arrow-right01 arrow-up01
cancel01 check-list checkmark-circle02 circle-dashed circle
computer computer-terminal01 copy01 delete02 file-diff file01 folder01
git-branch globe hand help-circle image-add01 image01 link01 loading03 mark-cross more-horizontal
notification01 notification-off01 pencil-edit01 pencil-edit02 refresh01 search01 share02 square square-lock02
user wrench01 settings01 gauge
""".split()

SVG = "{http://www.w3.org/2000/svg}"


def circle_path(cx, cy, r):
    """A circle as two arcs, since a vector drawable has no circle element."""
    return (f"M{cx - r:g},{cy}a{r:g},{r:g} 0 1,0 {2 * r:g},0"
            f"a{r:g},{r:g} 0 1,0 {-2 * r:g},0Z")


def rect_path(x, y, w, h, rx, ry):
    if not rx and not ry:
        return f"M{x:g},{y:g}h{w:g}v{h:g}h{-w:g}Z"
    rx = rx or ry
    ry = ry or rx
    return (f"M{x + rx:g},{y:g}h{w - 2 * rx:g}a{rx:g},{ry:g} 0 0,1 {rx:g},{ry:g}"
            f"v{h - 2 * ry:g}a{rx:g},{ry:g} 0 0,1 {-rx:g},{ry:g}"
            f"h{-(w - 2 * rx):g}a{rx:g},{ry:g} 0 0,1 {-rx:g},{-ry:g}"
            f"v{-(h - 2 * ry):g}a{rx:g},{ry:g} 0 0,1 {rx:g},{-ry:g}Z")


def num(el, name):
    return float(el.get(name, "0"))


def transform(el, name):
    """An element's transform as a matrix (a, b, c, d, e, f), or None."""
    t = el.get("transform")
    if not t:
        return None
    m = re.fullmatch(r"\s*(matrix|translate)\(([^)]*)\)\s*", t)
    if not m:
        sys.exit(f"{name}.svg: no support for transform {t!r}")
    v = [float(x) for x in re.split(r"[\s,]+", m.group(2).strip())]
    if m.group(1) == "translate":
        return (1, 0, 0, 1, v[0], v[1] if len(v) > 1 else 0)
    return tuple(v)


def circle(el, name):
    """A circle's path, its transform applied: a vector drawable has neither."""
    cx, cy, r = num(el, "cx"), num(el, "cy"), num(el, "r")
    m = transform(el, name)
    if m:
        a, b, c, d, e, f = m
        # Only a move, a mirror or an even scale keeps a circle a circle.
        if abs(abs(a * d - b * c) - (a * a + b * b)) > 1e-9 or abs(a * c + b * d) > 1e-9:
            sys.exit(f"{name}.svg: a transform that bends a circle")
        cx, cy = a * cx + c * cy + e, b * cx + d * cy + f
        r *= (a * a + b * b) ** 0.5
    return circle_path(cx, cy, r)


def viewbox(root, name):
    v = root.get("viewBox")
    if not v:
        sys.exit(f"{name}.svg: no viewBox")
    x, y, w, h = (float(n) for n in re.split(r"[\s,]+", v.strip()))
    if x or y:
        sys.exit(f"{name}.svg: a viewBox that does not start at 0,0")
    return w, h


def icon(name):
    tree = ET.parse(os.path.join(ICONS, name + ".svg"))
    # The icon is drawn at 24dp whatever its viewBox, as the desktop draws it.
    vw, vh = viewbox(tree.getroot(), name)
    paths = []
    for el in tree.iter():
        tag = el.tag.replace(SVG, "")
        if tag in ("svg", "g", "defs"):
            if tag == "g" and el.get("transform"):
                sys.exit(f"{name}.svg: no support for a transformed <g>")
            continue
        if tag == "path":
            if el.get("transform"):
                sys.exit(f"{name}.svg: no support for a transformed <path>")
            d = el.get("d")
        elif tag == "circle":
            d = circle(el, name)
        else:
            sys.exit(f"{name}.svg: no support for <{tag}>")
        stroke = el.get("stroke")
        fill = el.get("fill")
        attrs = [f'android:pathData="{d}"']
        if stroke and stroke != "none":
            attrs.append('android:strokeColor="#FF000000"')
            attrs.append(f'android:strokeWidth="{el.get("stroke-width", "1")}"')
            if el.get("stroke-linecap"):
                attrs.append(f'android:strokeLineCap="{el.get("stroke-linecap")}"')
            if el.get("stroke-linejoin"):
                attrs.append(f'android:strokeLineJoin="{el.get("stroke-linejoin")}"')
        if fill and fill != "none":
            attrs.append('android:fillColor="#FF000000"')
        paths.append("    <path\n        " + "\n        ".join(attrs) + " />")
    return (
        "<!-- Generated by android/tools/vectors.py from assets/icons/" + name + ".svg. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="24dp"\n    android:height="24dp"\n'
        f'    android:viewportWidth="{vw:g}"\n    android:viewportHeight="{vh:g}">\n'
        + "\n".join(paths) + "\n</vector>\n"
    )


def launcher(monochrome=False, canvas=108, size=48.0):
    """The raccoon in the middle of an adaptive icon's 108-unit canvas, as wide
    as on the iOS icon: two thirds of the 72 units a launcher shows. With a
    smaller canvas, the status bar's notification icon."""
    s = open(os.path.join(ROOT, "assets", "brand", "raccoon.svg")).read()
    w, h = 178.54, 137.16
    k = size / w
    tx = (canvas - size) / 2
    ty = (canvas - h * k) / 2
    colors = {"cls-1": "#FFFFB547", "cls-2": "#FFF1EFE8", "cls-3": "#FF151515", None: "#FF151515"}
    out = []
    for m in re.finditer(r"<(path|rect)\b([^>]*)/?>", s):
        tag, attrs = m.group(1), m.group(2)
        a = dict(re.findall(r'([\w-]+)="([^"]*)"', attrs))
        if tag == "path":
            d = a["d"]
        else:
            d = rect_path(float(a["x"]), float(a["y"]), float(a["width"]), float(a["height"]),
                          float(a.get("rx", 0)), float(a.get("ry", 0)))
        cls = a.get("class")
        # Themed icons draw everything in one tone: the fur alone, with the
        # mask and the ears as holes, still reads as the raccoon.
        if monochrome and cls != "cls-2":
            continue
        even = ' android:fillType="evenOdd"' if cls in ("cls-2", "cls-3") else ""
        out.append(f'        <path android:fillColor="{colors[cls]}"{even}\n'
                   f'            android:pathData="{d}" />')
    return (
        "<!-- Generated by android/tools/vectors.py from assets/brand/raccoon.svg. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        f'    android:width="{canvas}dp"\n    android:height="{canvas}dp"\n'
        f'    android:viewportWidth="{canvas}"\n    android:viewportHeight="{canvas}">\n'
        f'    <group android:translateX="{tx:.3f}" android:translateY="{ty:.3f}"\n'
        f'        android:scaleX="{k:.5f}" android:scaleY="{k:.5f}">\n'
        + "\n".join(out) + "\n    </group>\n</vector>\n"
    )


def main():
    os.makedirs(OUT, exist_ok=True)
    for old in os.listdir(OUT):
        if old.startswith("ic_") and old.endswith(".xml"):
            os.remove(os.path.join(OUT, old))
    for name in USED:
        with open(os.path.join(OUT, "ic_" + name.replace("-", "_") + ".xml"), "w") as f:
            f.write(icon(name))
    with open(os.path.join(OUT, "ic_launcher_foreground.xml"), "w") as f:
        f.write(launcher())
    with open(os.path.join(OUT, "ic_launcher_monochrome.xml"), "w") as f:
        f.write(launcher(monochrome=True))
    # The status bar draws only the shape, in white.
    with open(os.path.join(OUT, "ic_notification.xml"), "w") as f:
        f.write(launcher(monochrome=True, canvas=24, size=22.0).replace("#FFF1EFE8", "#FFFFFFFF"))
    print(f"wrote {len(USED)} icons, the launcher foreground and the notification icon to {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
